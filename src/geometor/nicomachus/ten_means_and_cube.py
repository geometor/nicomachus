r"""Ten Nicomachean Proportions & the Cube Harmony 6 : 8 :: 9 : 12 (Book II, Chs. 21–29).

Formalizes the culminating chapters of Nicomachus of Gerasa's *Introduction to Arithmetic*:

- **All Ten Means** (*δέκα μεσότητες*, II.21–28):

  - The three classical archetypes from Pythagoras, Archytas, Plato, and Aristotle:
    **1. Arithmetic**, **2. Geometric**, **3. Harmonic**.
  - The three subcontrary proportions (*ὑπεναντίαι*): **4. Subcontrary to Harmonic**,
    **5. First Subcontrary to Geometric**, **6. Second Subcontrary to Geometric**.
  - The four later Neo-Pythagorean proportions (*τέσσαρες ἕτεραι*, Myonides & Euphranor):
    **7th, 8th, 9th, and 10th** — where the **10th Mean** (:math:`(z - x)/(z - m) = m/x`)
    reduces for :math:`m \ne x` to the Fibonacci additive law :math:`x + m = z`
    (canonical example :math:`3, 5, 8`).

- **Semicircle Construction of the Three Classical Means** (*cf.* Pappus *Synagoge* III):
  Exact :class:`~geometor.model.Model` construction proving visually :math:`A \ge G \ge H` and
  :math:`A \cdot H = G^2`.
- **The Most Perfect Proportion (*Τελειοτάτη Ἀναλογία*, II.29)**:
  :math:`6 : 8 :: 9 : 12`, uniting the topology of the **Cube** (``6`` faces, ``8`` vertices,
  ``12`` edges — Philolaus's "geometric harmony"), Arithmetic (``9``), Harmonic (``8``), and
  Geometric (:math:`6 \cdot 12 = 8 \cdot 9 = 72`) symmetry, projective harmonic cross-ratio
  :math:`(6, 12; 8, 0) = -1`, and all Pythagorean musical consonances.
"""

