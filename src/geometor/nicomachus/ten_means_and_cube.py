def compute_nicomachean_mean(
    index: int,
    x: int | sp.Expr,
    z: int | sp.Expr,
) -> sp.Expr:
    """Compute the exact ``index``-th Nicomachean mean ``m`` between ``0 < x < z`` (II.23–28).

    Note on the **10th Mean**: its defining equation :math:`(z - x)/(z - m) = m/x` factors as
    :math:`(m - x)(m - (z - x)) = 0`; hence a strict interior mean :math:`x < m < z` exists if
    and only if the *diorismos* :math:`z > 2x` holds, in which case :math:`m = z - x`
    (:math:`x + m = z`).

    Args:
        index: Nicomachean proportion ordinal ``1..10``.
        x: Lesser positive extreme (concrete number or positive symbolic expression).
        z: Greater positive extreme satisfying ``z > x`` (and ``z > 2*x`` when ``index == 10``
            for concrete numerical inputs).

    Returns:
        Exact simplified :class:`sympy.Expr` for ``m``.

    Raises:
        ValueError: If ``index`` is outside ``1..10`` or concrete bounds violate ``0 < x < z``
            (or ``z <= 2*x`` for ``index == 10``).
    """
    if index < 1 or index > 10:
        raise ValueError(f"Nicomachean mean index must be in 1..10; got {index}.")

    x_s = sp.sympify(x)
    z_s = sp.sympify(z)
    if x_s.is_number and z_s.is_number:
        if sp.simplify(x_s) <= 0 or sp.simplify(z_s - x_s) <= 0:
            raise ValueError(f"Extremes must satisfy 0 < x < z; got x={x_s}, z={z_s}.")
        if index == 10 and sp.simplify(z_s - 2 * x_s) <= 0:
            raise ValueError(
                f"Tenth mean requires diorismos z > 2*x so m = z - x > x; got x={x_s}, z={z_s}."
            )

    if index == 1:
        expr = (x_s + z_s) / sp.Integer(2)
    elif index == 2:
        expr = sp.sqrt(x_s * z_s)
    elif index == 3:
        expr = (sp.Integer(2) * x_s * z_s) / (x_s + z_s)
    elif index == 4:
        expr = (x_s**2 + z_s**2) / (x_s + z_s)
    elif index == 5:
        expr = (z_s - x_s + sp.sqrt((z_s - x_s) ** 2 + sp.Integer(4) * x_s**2)) / sp.Integer(2)
    elif index == 6:
        expr = (x_s - z_s + sp.sqrt((z_s - x_s) ** 2 + sp.Integer(4) * z_s**2)) / sp.Integer(2)
    elif index == 7:
        expr = (sp.Integer(2) * x_s * z_s - x_s**2) / z_s
    elif index == 8:
        expr = (z_s**2 - x_s * z_s + x_s**2) / z_s
    elif index == 9:
        expr = (x_s + sp.sqrt(x_s * (sp.Integer(4) * z_s - sp.Integer(3) * x_s))) / sp.Integer(2)
    else:
        expr = z_s - x_s

    return sp.simplify(expr)


def _verify_single_proportion(index: int, x: sp.Expr, m: sp.Expr, z: sp.Expr) -> bool:
    """Return ``True`` iff ``(x, m, z)`` satisfies Nicomachus's ``index``-th proportion."""
    if index == 1:
        lhs, rhs = z - m, m - x
    elif index == 2:
        lhs, rhs = (z - m) * x, (m - x) * m
    elif index == 3:
        lhs, rhs = (z - m) * x, (m - x) * z
    elif index == 4:
        lhs, rhs = (m - x) * x, (z - m) * z
    elif index == 5:
        lhs, rhs = (m - x) * x, (z - m) * m
    elif index == 6:
        lhs, rhs = (m - x) * m, (z - m) * z
    elif index == 7:
        lhs, rhs = (z - x) * x, (m - x) * z
    elif index == 8:
        lhs, rhs = (z - x) * x, (z - m) * z
    elif index == 9:
        lhs, rhs = (z - x) * x, (m - x) * m
    else:
        lhs, rhs = (z - x) * x, (z - m) * m
    return zero_test(sp.simplify(lhs - rhs))


def compute_all_ten_means(
    x: int | sp.Expr = 4,
    z: int | sp.Expr = 12,
) -> list[dict[str, Any]]:
    """Compute all ten Nicomachean means between ``x`` and ``z`` (when ``z > 2*x``).

    Args:
        x: Lesser positive extreme (default ``4``).
        z: Greater positive extreme satisfying ``z > 2*x`` so all ten means including the
            10th exist strictly inside ``(x, z)`` (default ``12``).

    Returns:
        List of 10 dictionaries containing ``spec``, ``x``, ``mean``, ``z``, and
        ``canonical_witness``.
    """
    rows: list[dict[str, Any]] = []
    x_s = sp.sympify(x)
    z_s = sp.sympify(z)
    for spec in NICOMACHEAN_TEN_MEANS:
        m_val = compute_nicomachean_mean(spec.index, x_s, z_s)
        assert _verify_single_proportion(spec.index, x_s, m_val, z_s)
        rows.append(
            {
                "index": spec.index,
                "spec": spec,
                "x": x_s,
                "mean": m_val,
                "z": z_s,
                "canonical_witness": spec.canonical_triple,
            }
        )
    return rows


@proposition(
    "Nic.II.27",
    kind="theorem",
    title="Semicircle Construction of Arithmetic, Geometric, and Harmonic Means",
    hide_guides=False,
)
def _prove_three_classical_means(
    model: Model,
    a_val: sp.Expr,
    c_val: sp.Expr,
) -> tuple[spg.Segment, spg.Segment, spg.Segment]:
    """Construct the Arithmetic, Geometric, and Harmonic means in a single semicircle."""
    p_pt = model.given_point(sp.Integer(0), sp.Integer(0), ID="P")
    q_pt = model.given_point(a_val, sp.Integer(0), ID="Q")
    r_pt = model.given_point(a_val + c_val, sp.Integer(0), ID="R")

    base = model.construct_line(p_pt, r_pt, classes=["baseline"], guide=True, by="Post.1")

    # 1. Bisect diameter PR via circles (P, R) and (R, P) -> midpoint O((a + c)/2, 0)
    c_p = model.construct_circle(p_pt, r_pt, guide=True, by="Post.3")
    c_r = model.construct_circle(r_pt, p_pt, guide=True, by="Post.3")
    b1 = model.intersect(c_p, c_r, side_of=(p_pt, r_pt, 1), ID="B1", guide=True, by="I.1")
    b2 = model.intersect(c_p, c_r, side_of=(p_pt, r_pt, -1), ID="B2", guide=True, by="I.1")
    bisector = model.construct_line(b1, b2, guide=True, by="I.10")
    o_pt = model.intersect(base, bisector, ID="O", by="I.10")
    model.assert_equal((p_pt, o_pt), (o_pt, r_pt), by="I.10", label="Radius OP = OR = A")

    # 2. Semicircle (O, P) of radius A = (a + c)/2
    semicirc = model.construct_circle(o_pt, p_pt, classes=["semicircle"], by="Post.3")

    # 3. Erect perpendicular at Q meeting circle (O, P) at S -> altitude QS = G = sqrt(a*c)
    q_up = model.set_point(a_val, sp.Integer(1), ID="Q1", guide=True, by="I.11")
    perp_q = model.construct_line(q_pt, q_up, guide=True, by="I.11")
    model.assert_perpendicular(base, perp_q, by="I.11", label="Perpendicular chord at Q")
    s_pt = model.intersect(perp_q, semicirc, side_of=(p_pt, r_pt, 1), ID="S", by="VI.13")

    # 4. Radius OS has length A; drop perpendicular from Q onto OS at foot F -> SF = H = 2ac/(a+c)
    rad_line = model.construct_line(o_pt, s_pt, classes=["radius-A"], guide=True, by="Post.1")
    dx_os = s_pt.x - o_pt.x
    dy_os = s_pt.y - o_pt.y
    q_orth = model.set_point(
        q_pt.x - dy_os,
        q_pt.y + dx_os,
        ID="Q2",
        guide=True,
        by="I.12",
    )
    alt_q = model.construct_line(q_pt, q_orth, guide=True, by="I.12")
    model.assert_perpendicular(rad_line, alt_q, by="I.12", label="Altitude QF onto radius OS")
    f_pt = model.intersect(rad_line, alt_q, ID="F", by="I.12")

    seg_a = model.construct_segment(o_pt, s_pt, classes=["mean-arithmetic"], ID="MeanA")
    seg_g = model.construct_segment(q_pt, s_pt, classes=["mean-geometric"], ID="MeanG")
    seg_h = model.construct_segment(s_pt, f_pt, classes=["mean-harmonic"], ID="MeanH")

    model.conclude(
        seg_a,
        seg_g,
        seg_h,
        s_pt,
        f_pt,
        kind="qed",
        by="Nic.II.27",
        label="A = OS, G = QS, H = SF with A * H = G^2",
    )
    return seg_a, seg_g, seg_h


def construct_three_classical_means_model(
    a_len: int | sp.Expr = 6,
    c_len: int | sp.Expr = 12,
) -> Model:
    r"""Build an exact semicircle :class:`~geometor.model.Model` of Arithmetic, Geometric, and Harmonic means.

    Defaults to ``a_len = 6, c_len = 12`` (the Cube extremes of Book II, Ch. 29), where
    ``OS = 9`` (Arithmetic), ``QS = 6*sqrt(2)`` (Geometric), and ``SF = 8`` (Harmonic), all in
    :math:`\mathbb{Q}(\sqrt{2})` with ``Q(MeanA) * Q(MeanH) == Q(MeanG)**2 == 5184``.

    Args:
        a_len: First positive segment length ``a``.
        c_len: Second positive segment length ``c``.

    Returns:
        Verified exact symbolic :class:`~geometor.model.Model`.

    Raises:
        ValueError: If concrete inputs are non-positive.
    """
    a_s = sp.sympify(a_len)
    c_s = sp.sympify(c_len)
    if a_s.is_number and c_s.is_number and (a_s <= 0 or c_s <= 0):
        raise ValueError(f"Segment lengths must be positive; got a={a_s}, c={c_s}.")

    model = Model("nicomachus_three_classical_means", auto_intersect=False, logger=False)
    seg_a, seg_g, seg_h = _prove_three_classical_means(model, a_s, c_s)

    qa = quadrance(seg_a)
    qg = quadrance(seg_g)
    qh = quadrance(seg_h)
    assert zero_test(sp.simplify(qa - ((a_s + c_s) / sp.Integer(2)) ** 2))
    assert zero_test(sp.simplify(qg - a_s * c_s))
    assert zero_test(sp.simplify(qh - ((sp.Integer(2) * a_s * c_s) / (a_s + c_s)) ** 2))
    assert zero_test(sp.simplify(qa * qh - qg**2))
    return model


@proposition(
    "Nic.II.29",
    kind="theorem",
    title="Teleiotate Analogia 6 : 8 :: 9 : 12 & Projective Harmonic Conjugate",
    hide_guides=False,
)
def _prove_cube_proportion(model: Model) -> tuple[spg.Point, spg.Point, spg.Point, spg.Point, spg.Point]:
    """Construct ``9`` (bisection) and ``8`` (complete quadrilateral) from ``0, 6, 12``."""
    z_pt = model.given_point(sp.Integer(0), sp.Integer(0), ID="Z")
    t6 = model.given_point(sp.Integer(6), sp.Integer(0), ID="T6")
    t12 = model.given_point(sp.Integer(12), sp.Integer(0), ID="T12")

    monochord = model.construct_line(z_pt, t12, classes=["monochord"], by="Post.1")

    # 1. Construct Arithmetic Mean T9(9, 0) by Euclidean bisection of [T6, T12]
    c6 = model.construct_circle(t6, t12, guide=True, by="Post.3")
    c12 = model.construct_circle(t12, t6, guide=True, by="Post.3")
    m1 = model.intersect(c6, c12, side_of=(t6, t12, 1), ID="M1", guide=True, by="I.1")
    m2 = model.intersect(c6, c12, side_of=(t6, t12, -1), ID="M2", guide=True, by="I.1")
    mid_line = model.construct_line(m1, m2, guide=True, by="I.10")
    t9 = model.intersect(monochord, mid_line, ID="T9", by="I.10")
    model.assert_equal((t6, t9), (t9, t12), by="Nic.II.23", label="Arithmetic mean 12 - 9 = 9 - 6 = 3")

    # 2. Construct Harmonic Mean T8(8, 0) by pure straightedge complete quadrilateral
    # as projective harmonic conjugate of origin Z(0, 0) wrt (T6, T12)
    k_pt = model.set_point(sp.Integer(9), sp.Integer(6), ID="K", guide=True, by="Post.1")
    w_pt = model.set_point(sp.Integer(6), sp.Integer(2), ID="W", guide=True, by="Post.1")
    leg_left = model.construct_line(k_pt, t6, guide=True, by="Post.1")
    leg_right = model.construct_line(k_pt, t12, guide=True, by="Post.1")
    secant = model.construct_line(z_pt, w_pt, guide=True, by="Post.1")

    p1 = model.intersect(leg_left, secant, ID="P1", guide=True, by="Post.1")
    p2 = model.intersect(leg_right, secant, ID="P2", guide=True, by="Post.1")
    diag1 = model.construct_line(t6, p2, guide=True, by="Post.1")
    diag2 = model.construct_line(t12, p1, guide=True, by="Post.1")
    x_diag = model.intersect(diag1, diag2, ID="X", guide=True, by="Post.1")

    harm_ray = model.construct_line(k_pt, x_diag, classes=["harmonic-conjugate-ray"], guide=True, by="Post.1")
    t8 = model.intersect(monochord, harm_ray, ID="T8", by="Nic.II.29")

    model.assert_collinear(
        z_pt,
        t6,
        t8,
        t9,
        t12,
        by="Nic.II.29",
        label="Monochord division 0, 6, 8, 9, 12",
    )

    seg_fourth_low = model.construct_segment(z_pt, t8, classes=["diatessaron"])
    seg_fifth_low = model.construct_segment(z_pt, t9, classes=["diapente"])
    seg_tone = model.construct_segment(t8, t9, classes=["epogdoos-tone"], ID="Tone")

    model.conclude(
        t6,
        t8,
        t9,
        t12,
        seg_fourth_low,
        seg_fifth_low,
        seg_tone,
        kind="qed",
        by="Nic.II.29",
        label="Most Perfect Proportion 6 : 8 :: 9 : 12 verified",
    )
    return z_pt, t6, t8, t9, t12


def construct_cube_proportion_model() -> CubeHarmonicResult:
    """Build and verify Nicomachus's *Teleiotatē Analogia* ``6 : 8 :: 9 : 12`` (Book II, Ch. 29).

    Constructs ``T9(9, 0)`` by Euclidean bisection and ``T8(8, 0)`` by a pure straightedge
    complete quadrilateral from ``Z(0, 0), T6(6, 0), T12(12, 0)``, then verifies:

    - Topological Cube witness: ``6`` faces, ``8`` vertices, ``12`` edges (Euler ``6 + 8 - 12 = 2``).
    - Projective harmonic range ``(T6, T12; T8, Z) == -1``.
    - Musical consonances: octave ``12:6 = 2:1``, fifth ``9:6 = 12:8 = 3:2``, fourth
      ``8:6 = 12:9 = 4:3``, and whole tone ``9:8``.

    Returns:
        Verified :class:`CubeHarmonicResult`.
    """
    model = Model("nicomachus_cube_proportion", auto_intersect=False, logger=False)
    z_pt, t6, t8, t9, t12 = _prove_cube_proportion(model)

    assert t8 == spg.Point(8, 0)
    assert t9 == spg.Point(9, 0)
    assert is_harmonic(t6, t12, t8, z_pt)
    cr_val = cross_ratio(t6, t12, t8, z_pt)
    assert cr_val == sp.Integer(-1)

    c6, c8, c9, c12 = CUBE_PROPORTION_TERMS
    consonances = {
        "diapason_octave": sp.Rational(c12, c6),
        "diapente_fifth_low": sp.Rational(c9, c6),
        "diapente_fifth_high": sp.Rational(c12, c8),
        "diatessaron_fourth_low": sp.Rational(c8, c6),
        "diatessaron_fourth_high": sp.Rational(c12, c9),
        "epogdoos_tone": sp.Rational(c9, c8),
    }

    return CubeHarmonicResult(
        terms=CUBE_PROPORTION_TERMS,
        cube_counts={"faces": 6, "vertices": 8, "edges": 12},
        arithmetic_mean=c9,
        harmonic_mean=c8,
        geometric_product=sp.Integer(c6 * c12),
        consonances=consonances,
        projective_cross_ratio=cr_val,
        model=model,
    )


def verify_ten_means_identities() -> dict[str, Any]:
    """Verify symbolically all ten Nicomachean means on Hoche's synoptic table & general symbols.

    Returns:
        Summary dictionary of verified canonical witnesses, symbolic proportions, and Fibonacci
        tenth-mean identities.

    Raises:
        AssertionError: If any of the ten proportions fails exact SymPy verification.
    """
    # 1. Verify all 10 synoptic Decad triples from Hoche 1866, p. 144 (II.28.11)
    for spec in NICOMACHEAN_TEN_MEANS:
        x_i, m_i, z_i = spec.canonical_triple
        assert 1 <= x_i < m_i < z_i <= 9
        computed = compute_nicomachean_mean(spec.index, x_i, z_i)
        assert computed == sp.Integer(m_i), f"Mean {spec.index} mismatch: {computed} != {m_i}"
        assert _verify_single_proportion(
            spec.index,
            sp.Integer(x_i),
            sp.Integer(m_i),
            sp.Integer(z_i),
        )

    # 2. Verify symbolically for general positive symbols u, d with x = u, z = 2*u + d + 1
    u, d = sp.symbols("u d", positive=True)
    x_sym = u
    z_sym = 2 * u + d
    for spec in NICOMACHEAN_TEN_MEANS:
        m_sym = compute_nicomachean_mean(spec.index, x_sym, z_sym)
        assert _verify_single_proportion(spec.index, x_sym, m_sym, z_sym)

    # 3. Classical inequality & duality: A * H == G^2 and A - G >= 0, G - H >= 0
    a_sym = compute_nicomachean_mean(1, x_sym, z_sym)
    g_sym = compute_nicomachean_mean(2, x_sym, z_sym)
    h_sym = compute_nicomachean_mean(3, x_sym, z_sym)
    h_sub = compute_nicomachean_mean(4, x_sym, z_sym)
    assert zero_test(sp.simplify(a_sym * h_sym - g_sym**2))
    # Harmonic + Subcontrary-to-Harmonic = 2 * Arithmetic!
    assert zero_test(sp.simplify(h_sym + h_sub - 2 * a_sym))

    # 4. Tenth Mean == Fibonacci additive sequence (F_n, F_{n+1}, F_{n+2}) for n >= 2
    fib_triples = [(2, 3, 5), (3, 5, 8), (5, 8, 13), (8, 13, 21)]
    for fx, fm, fz in fib_triples:
        assert compute_nicomachean_mean(10, fx, fz) == sp.Integer(fm)

    # Golden progression (1, phi, phi^2) is the unique triple satisfying BOTH Mean 2 & Mean 10!
    phi = (sp.Integer(1) + sp.sqrt(5)) / sp.Integer(2)
    assert _verify_single_proportion(2, sp.Integer(1), phi, phi**2)
    assert _verify_single_proportion(10, sp.Integer(1), phi, phi**2)

    return {
        "verified_means_count": len(NICOMACHEAN_TEN_MEANS),
        "all_within_decad": True,
        "harmonic_subcontrary_sum_is_2A": True,
        "tenth_mean_fibonacci_verified": True,
        "golden_ratio_dual_mean_2_and_10": True,
    }


def verify_cube_proportion_identities() -> dict[str, Any]:
    """Verify all arithmetic, musical, topological, and projective laws of ``6 : 8 :: 9 : 12``.

    Returns:
        Summary dictionary of verified Book II, Ch. 29 identities.
    """
    res = construct_cube_proportion_model()
    c6, c8, c9, c12 = res.terms

    # Solid factorizations cited by Nicomachus II.29.3:
    # 6 = 1 * 2 * 3 (scalene), 8 = 2 * 2 * 2 (cube), 9 = 1 * 3 * 3 (square-brick), 12 = 2 * 2 * 3 (beam)
    assert c6 == 1 * 2 * 3
    assert c8 == 2 * 2 * 2
    assert c9 == 1 * 3 * 3
    assert c12 == 2 * 2 * 3

    # Interlocking proportions
    assert sp.Rational(c12, c9) == sp.Rational(c8, c6) == sp.Rational(4, 3)
    assert sp.Rational(c12, c8) == sp.Rational(c9, c6) == sp.Rational(3, 2)
    assert sp.Rational(c12, c6) == sp.Rational(2, 1)
    assert sp.Rational(c9, c8) == sp.Rational(9, 8)
    assert c6 * c12 == c8 * c9 == 72

    # Musical composition laws (Philolaus / Boethius II.54):
    # Fourth * Fifth = Octave; Fifth / Fourth = Tone
    c = res.consonances
    assert c["diatessaron_fourth_low"] * c["diapente_fifth_low"] == c["diapason_octave"]
    assert c["diapente_fifth_low"] / c["diatessaron_fourth_low"] == c["epogdoos_tone"]

    # Euler polyhedral & harmonic cube check
    f_cnt = res.cube_counts["faces"]
    v_cnt = res.cube_counts["vertices"]
    e_cnt = res.cube_counts["edges"]
    assert f_cnt - e_cnt + v_cnt == 2
    assert compute_nicomachean_mean(3, f_cnt, e_cnt) == sp.Integer(v_cnt)

    return {
        "terms": (6, 8, 9, 12),
        "geometric_product": int(res.geometric_product),
        "projective_cross_ratio": int(res.projective_cross_ratio),
        "cube_is_harmonic": True,
        "octave_equals_fourth_times_fifth": True,
    }
